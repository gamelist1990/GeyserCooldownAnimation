#!/usr/bin/env python3
"""Build the lab-only deterministic skin extension using NumPy/Pillow Python."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import subprocess
import zipfile
from PIL import Image, ImageDraw


def build(server, output, profile_property, shape='wide', layered=False):
    if not (server / 'lab.json').is_file():
        raise ValueError('Only the isolated lab may supply build dependencies')
    if output.exists():
        raise ValueError('Use a new build directory')
    output.mkdir(parents=True)
    image = Image.new('RGBA', (64, 64))
    draw = ImageDraw.Draw(image)
    # Original, synthetic classic skin: all base surfaces opaque, no outer layer.
    for box, color in [((0,0,31,15), '#c99370'), ((16,16,39,31), '#20aabb'),
                       ((40,16,55,31), '#c99370'), ((32,48,47,63), '#c99370'),
                       ((0,16,15,31), '#24466b'), ((16,48,31,63), '#24466b')]:
        draw.rectangle(box, fill=color)
    draw.rectangle((10,11,10,11), fill='#202020')
    draw.rectangle((13,11,13,11), fill='#202020')
    draw.rectangle((11,14,12,14), fill='#503828')
    if layered:
        # Deliberate opaque patches and transparent holes exercise outer layers.
        for box in ((40,8,43,11), (20,36,23,43), (44,36,47,43),
                    (52,52,55,59), (4,36,7,43), (4,52,7,59)):
            draw.rectangle(box, fill='#517d35')
    image.save(output / 'fixture.png')
    skin = image.tobytes()
    source = Path(__file__).with_name('VisualLabSkin.java').resolve()
    dependency = (server / 'plugins/Geyser-Spigot.jar').resolve()
    classes = output / 'classes'; classes.mkdir()
    subprocess.run(['javac', '-cp', str(dependency), '-d', str(classes), str(source)], check=True)
    manifest = ('id: visuallabskin\nname: VisualLabSkin\nmain: VisualLabSkin\n'
                'api: 2.9.0\nversion: 0.1.0\nauthors: [VisualLab]\n')
    jar = output / 'VisualLabSkin-0.1.0.jar'
    with zipfile.ZipFile(jar, 'w', zipfile.ZIP_DEFLATED) as archive:
        archive.writestr('extension.yml', manifest)
        archive.writestr('fixture.rgba', skin)
        archive.writestr('fixture.shape', shape)
        for path in classes.glob('*.class'):
            archive.write(path, path.name)
    profile_source = Path(__file__).with_name('VisualLabProfile.java').resolve()
    dependencies = os.pathsep.join(str(path.resolve()) for path in sorted(server.glob('libraries/**/*.jar')))
    profile_classes = output / 'profile-classes'; profile_classes.mkdir()
    subprocess.run(['javac', '-cp', dependencies, '-d', str(profile_classes), str(profile_source)], check=True)
    with zipfile.ZipFile(output / 'VisualLabProfile-0.1.0.jar', 'w', zipfile.ZIP_DEFLATED) as archive:
        archive.writestr('plugin.yml', 'name: VisualLabProfile\nmain: VisualLabProfile\nversion: 0.1.0\napi-version: 1.21\n')
        property_data = json.loads(profile_property.read_text())
        if property_data.get('name') != 'textures' or not property_data.get('signature'):
            raise ValueError('Expected a public signed Mojang textures property')
        archive.writestr('profile.value', property_data['value'])
        archive.writestr('profile.signature', property_data['signature'])
        for path in profile_classes.glob('*.class'):
            archive.write(path, path.name)
    (output / 'skin.json').write_text(json.dumps(dict(
        shape=shape, layered=layered, sha256=hashlib.sha256(skin).hexdigest(),
        source='Original synthetic texture generated by build_skin_fixture.py'), indent=2)+'\n')
    print(jar)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--server-dir', type=Path, required=True)
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--profile-property', type=Path, required=True,
        help='Public signed textures property; not an account credential')
    parser.add_argument('--shape', choices=('wide', 'slim'), default='wide')
    parser.add_argument('--layered', action='store_true')
    args = parser.parse_args()
    build(args.server_dir, args.output, args.profile_property, args.shape, args.layered)
